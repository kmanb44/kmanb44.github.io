#!/usr/bin/env node
/**
 * Generates one small static page per blog post so Discord (and other link
 * preview bots that do not run JavaScript) can read per-post Open Graph tags.
 *
 * Each generated page immediately redirects to the matching post on the main
 * blog page, so the site itself is unchanged for visitors.
 *
 * Run with: node scripts/generate-blog-embeds.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const POSTS_FILE = path.join(ROOT, 'blog', 'posts.json');
const OUTPUT_DIR = path.join(ROOT, 'blog', 'posts');
const SITE_ORIGIN = 'https://kmanb44.github.io';
const GENERATED_MARKER = '<!-- Generated by scripts/generate-blog-embeds.mjs -->';

const escapeHtml = (value = '') => String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');

const postFileName = (id) => {
    const safeId = String(id).trim();
    if (!/^[A-Za-z0-9._-]+$/.test(safeId)) {
        throw new Error(`Post id "${safeId}" cannot be used as a URL filename. Use letters, numbers, dots, underscores, or hyphens.`);
    }
    return `${safeId}.html`;
};

const tagsFor = (tags) => (Array.isArray(tags) ? tags : [])
    .map((tag) => `#${String(tag).trim()}`)
    .filter((tag) => tag !== '#')
    .join(' · ');

const publishedAt = (date) => {
    if (!date) return '';
    const parsed = new Date(`${date}T00:00:00Z`);
    return Number.isNaN(parsed.getTime()) ? '' : parsed.toISOString();
};

const posts = JSON.parse(fs.readFileSync(POSTS_FILE, 'utf8'));

if (!Array.isArray(posts)) {
    throw new Error('blog/posts.json must contain an array of posts.');
}

fs.mkdirSync(OUTPUT_DIR, { recursive: true });

const generatedFiles = new Set();

for (const post of posts) {
    const id = String(post.id);
    const fileName = postFileName(id);
    const title = post.title || 'Untitled post';
    const subtitle = post.subtitle || '';
    const tags = tagsFor(post.tags);
    const postUrl = `${SITE_ORIGIN}/blog/posts/${encodeURIComponent(fileName)}`;
    const canonicalUrl = `${SITE_ORIGIN}/blog/kmanGPT.html#post-${encodeURIComponent(id)}`;
    const redirectUrl = `../kmanGPT.html#post-${encodeURIComponent(id)}`;
    const pubdate = publishedAt(post.date);

    const html = `<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    ${GENERATED_MARKER}
    <title>${escapeHtml(title)} | kmanGPT Developer Logs</title>
    <link rel="canonical" href="${escapeHtml(canonicalUrl)}">

    <!-- Open Graph: read by Discord when the link is shared. -->
    <meta property="og:type" content="article">
    <meta property="og:site_name" content="${escapeHtml(tags || 'kmanGPT Developer Logs')}">
    <meta property="og:title" content="${escapeHtml(title)}">
    <meta property="og:description" content="${escapeHtml(subtitle)}">
    <meta property="og:url" content="${escapeHtml(postUrl)}">
    ${pubdate ? `<meta property="og:pubdate" content="${escapeHtml(pubdate)}">` : ''}
    <meta name="twitter:card" content="summary">
    <meta name="twitter:title" content="${escapeHtml(title)}">
    <meta name="twitter:description" content="${escapeHtml(subtitle)}">
    <meta name="theme-color" content="#00e5ff">

    <meta http-equiv="refresh" content="0;url=${escapeHtml(redirectUrl)}">
    <script>window.location.replace(${JSON.stringify(redirectUrl)});</script>
</head>
<body>
    <p>Redirecting to <a href="${escapeHtml(redirectUrl)}">${escapeHtml(title)}</a>&hellip;</p>
</body>
</html>
`;

    fs.writeFileSync(path.join(OUTPUT_DIR, fileName), html, 'utf8');
    generatedFiles.add(fileName);
}

// Remove pages for posts that no longer exist, but only files this script made.
for (const fileName of fs.readdirSync(OUTPUT_DIR)) {
    if (!fileName.endsWith('.html') || generatedFiles.has(fileName)) continue;

    const filePath = path.join(OUTPUT_DIR, fileName);
    if (fs.readFileSync(filePath, 'utf8').includes(GENERATED_MARKER)) {
        fs.unlinkSync(filePath);
    }
}

console.log(`Generated ${generatedFiles.size} blog embed page(s) in blog/posts/.`);
